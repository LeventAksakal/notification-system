// Command schemadiff turns schema/ (the desired state) into goose migrations
// with sqldef, and checks that migrations/ and schema/ agree.
//
// schema/ may hold any number of .sql files in any folders; they are read in
// path order, so a table that others reference must sort first. The current
// state is a scratch MySQL that has migrations/ applied (task migrate:diff
// prepares it).
//
//	schemadiff -name add_note    write migrations/<UTC time>_add_note.sql
//	schemadiff -check            exit 1 if schema/ differs from the scratch database
//
// Two gaps of mysqldef (v3.11.30) are closed here: it never drops a MySQL
// trigger that schema/ no longer declares (so Up, Down and -check compare
// trigger names themselves), and a trigger body holds semicolons, so each
// CREATE TRIGGER is wrapped in goose's StatementBegin/StatementEnd.
//
// sqlc's MySQL parser rejects CREATE TRIGGER, so sqlc reads sqlcSchema: the
// scratch database's export after the migrations, without its triggers.
// -name rewrites it; -check fails when it is stale.
package main

import (
	"bufio"
	"bytes"
	"context"
	"database/sql"
	"errors"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"
	"time"

	"github.com/go-sql-driver/mysql"
)

// sqlcSchema is the schema sqlc reads (sqlc.yaml).
const sqlcSchema = "internal/store/schema.gen.sql"

const sqlcSchemaHeader = "-- Code generated by tools/schemadiff from migrations/; DO NOT EDIT.\n" +
	"-- The schema sqlc reads: MySQL's export of the migrated database without its\n" +
	"-- triggers, which sqlc's parser cannot read. Edit schema/, then run task migrate:diff.\n\n"

func main() {
	name := flag.String("name", "", "migration name (writes the next migration)")
	check := flag.Bool("check", false, "fail if schema/ and the scratch database differ")
	host := flag.String("host", "127.0.0.1", "scratch MySQL host")
	port := flag.String("port", "33306", "scratch MySQL port")
	db := flag.String("db", "dev", "scratch database")
	flag.Parse()
	conn := []string{"-uroot", "-h" + *host, "-P" + *port, *db}
	cfg := mysql.NewConfig()
	cfg.User, cfg.Passwd, cfg.Net, cfg.Addr, cfg.DBName = "root", "dev", "tcp", *host+":"+*port, *db

	if err := run(*name, *check, conn, cfg.FormatDSN()); err != nil {
		fmt.Fprintln(os.Stderr, "schemadiff:", err)
		os.Exit(1)
	}
}

func run(name string, check bool, conn []string, dsn string) error {
	if (name == "") == !check {
		return errors.New("give exactly one of -name or -check")
	}
	tmp, err := os.MkdirTemp("", "schemadiff")
	if err != nil {
		return fmt.Errorf("making a temp folder: %w", err)
	}
	defer func() { _ = os.RemoveAll(tmp) }()

	desired := filepath.Join(tmp, "desired.sql")
	if err := concatSchema("schema", desired); err != nil {
		return err
	}

	desiredSQL, err := os.ReadFile(desired) //nolint:gosec // G304: written above
	if err != nil {
		return fmt.Errorf("reading the desired schema: %w", err)
	}
	before, err := export(conn, filepath.Join(tmp, "before.sql"))
	if err != nil {
		return err
	}
	beforeSQL, err := os.ReadFile(before) //nolint:gosec // G304: written above
	if err != nil {
		return fmt.Errorf("reading the export: %w", err)
	}
	stale := missing(triggerNames(string(beforeSQL)), triggerNames(string(desiredSQL)))

	if check {
		if have, err := os.ReadFile(sqlcSchema); err != nil || string(have) != sqlcSchemaHeader+stripTriggers(string(beforeSQL)) {
			return fmt.Errorf("%s does not match migrations/; run task migrate:diff -- <name>", sqlcSchema)
		}
		if len(stale) > 0 {
			return fmt.Errorf("schema/ and migrations/ disagree: migrations/ keep triggers schema/ no longer declares (%s); run task migrate:diff -- <name>", strings.Join(stale, ", "))
		}
		out, code, err := mysqldef(append([]string{"--check", "--enable-drop", "--file", desired}, conn...)...)
		if err != nil {
			return err
		}
		if code == 2 {
			return fmt.Errorf("schema/ and migrations/ disagree; run task migrate:diff -- <name>\n%s", out)
		}
		if code != 0 {
			return fmt.Errorf("mysqldef exited %d\n%s", code, out)
		}
		return nil
	}

	up, err := statements(append([]string{"--dry-run", "--enable-drop", "--file", desired}, conn...)...)
	if err != nil {
		return err
	}
	up = dropTriggers(stale) + up
	if up == "" {
		fmt.Println("schema/ matches migrations/; nothing to write")
		return writeSQLCSchema(string(beforeSQL))
	}
	// Down: apply Up to the scratch database, then diff its export back to
	// the export from before. Both sides are MySQL's own spelling, so the
	// diff holds only the real change.
	if err := dropOnScratch(dsn, stale); err != nil {
		return err
	}
	if _, err := statements(append([]string{"--apply", "--enable-drop", "--file", desired}, conn...)...); err != nil {
		return fmt.Errorf("applying the change to the scratch database: %w", err)
	}
	after, err := export(conn, filepath.Join(tmp, "after.sql"))
	if err != nil {
		return err
	}
	afterSQL, err := os.ReadFile(after) //nolint:gosec // G304: written above
	if err != nil {
		return fmt.Errorf("reading the export: %w", err)
	}
	down, err := statements("--enable-drop", "--file", before, after) // offline: from after back to before
	if err != nil {
		return err
	}
	// Triggers first: a later statement of Down may drop a column they read.
	down = dropTriggers(missing(triggerNames(string(afterSQL)), triggerNames(string(beforeSQL)))) + down

	path := filepath.Join("migrations", time.Now().UTC().Format("20060102150405")+"_"+name+".sql")
	body := "-- +goose Up\n" + wrapTriggers(up) + "\n-- +goose Down\n" + wrapTriggers(down)
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		return fmt.Errorf("writing %s: %w", path, err)
	}
	fmt.Println("wrote", path)
	return writeSQLCSchema(string(afterSQL))
}

// writeSQLCSchema writes sqlcSchema from an export of the scratch database.
func writeSQLCSchema(export string) error {
	if err := os.WriteFile(sqlcSchema, []byte(sqlcSchemaHeader+stripTriggers(export)), 0o600); err != nil {
		return fmt.Errorf("writing %s: %w", sqlcSchema, err)
	}
	return nil
}

// export writes the scratch database's schema to path and returns path.
func export(conn []string, path string) (string, error) {
	out, code, err := mysqldef(append([]string{"--export"}, conn...)...)
	if err != nil || code != 0 {
		return "", fmt.Errorf("exporting the scratch schema (exit %d): %w\n%s", code, err, out)
	}
	if err := os.WriteFile(path, []byte(out), 0o600); err != nil {
		return "", fmt.Errorf("writing %s: %w", path, err)
	}
	return path, nil
}

// concatSchema writes every .sql file under dir, in path order, into out.
func concatSchema(dir, out string) error {
	var files []string
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && strings.HasSuffix(p, ".sql") {
			files = append(files, p)
		}
		return nil
	})
	if err != nil {
		return fmt.Errorf("listing %s: %w", dir, err)
	}
	sort.Strings(files)
	var b bytes.Buffer
	for _, f := range files {
		data, err := os.ReadFile(f) //nolint:gosec // G304: paths come from walking schema/
		if err != nil {
			return fmt.Errorf("reading %s: %w", f, err)
		}
		b.Write(data)
		b.WriteString("\n")
	}
	if err := os.WriteFile(out, b.Bytes(), 0o600); err != nil {
		return fmt.Errorf("writing the desired schema: %w", err)
	}
	return nil
}

// statements runs mysqldef and keeps only the DDL: no dry-run banner, no
// BEGIN/COMMIT wrapper (MySQL DDL commits implicitly; goose wraps each file).
func statements(args ...string) (string, error) {
	out, code, err := mysqldef(args...)
	if err != nil {
		return "", err
	}
	if code != 0 {
		return "", fmt.Errorf("mysqldef exited %d\n%s", code, out)
	}
	var b strings.Builder
	sc := bufio.NewScanner(strings.NewReader(out))
	for sc.Scan() {
		line := sc.Text()
		switch strings.TrimSpace(line) {
		case "-- dry run --", "BEGIN;", "COMMIT;", "-- Nothing is modified --", "":
			continue
		}
		if strings.HasPrefix(line, "-- Skipped:") {
			return "", fmt.Errorf("mysqldef skipped a statement: %s", line)
		}
		b.WriteString(line + "\n")
	}
	return b.String(), sc.Err()
}

// mysqldef runs the pinned mysqldef (tools.mod) with the scratch password.
func mysqldef(args ...string) (string, int, error) {
	cmd := exec.CommandContext(context.Background(), "go", append([]string{"tool", "-modfile=tools.mod", "mysqldef", "--config-inline", "skip_tables: goose_db_version"}, args...)...) //nolint:gosec // G204: fixed tool, arguments built here
	cmd.Env = append(os.Environ(), "MYSQL_PWD=dev")
	out, err := cmd.CombinedOutput()
	var exit *exec.ExitError
	if errors.As(err, &exit) {
		return string(out), exit.ExitCode(), nil
	}
	if err != nil {
		return string(out), 0, fmt.Errorf("running mysqldef: %w", err)
	}
	return string(out), 0, nil
}

// triggerRE finds the name of each CREATE TRIGGER, in sqldef's and MySQL's spelling.
var triggerRE = regexp.MustCompile("(?im)^\\s*CREATE\\s+TRIGGER\\s+(?:IF\\s+NOT\\s+EXISTS\\s+)?`?([A-Za-z0-9_$]+)`?")

// triggerNames lists the triggers a SQL text creates, sorted, lower case.
func triggerNames(sqlText string) []string {
	var names []string
	for _, m := range triggerRE.FindAllStringSubmatch(sqlText, -1) {
		names = append(names, strings.ToLower(m[1]))
	}
	sort.Strings(names)
	return slices.Compact(names)
}

// missing returns the names in have that want does not hold.
func missing(have, want []string) []string {
	var out []string
	for _, n := range have {
		if !slices.Contains(want, n) {
			out = append(out, n)
		}
	}
	return out
}

// dropTriggers is one DROP TRIGGER statement per name.
func dropTriggers(names []string) string {
	var b strings.Builder
	for _, n := range names {
		fmt.Fprintf(&b, "DROP TRIGGER IF EXISTS `%s`;\n", n)
	}
	return b.String()
}

// dropOnScratch drops the named triggers on the scratch database, which
// mysqldef cannot do, so the export after Up matches the migration.
func dropOnScratch(dsn string, triggers []string) error {
	if len(triggers) == 0 {
		return nil
	}
	db, err := sql.Open("mysql", dsn)
	if err != nil {
		return fmt.Errorf("opening the scratch database: %w", err)
	}
	defer func() { _ = db.Close() }()
	for _, n := range triggers {
		if _, err := db.ExecContext(context.Background(), "DROP TRIGGER IF EXISTS `"+n+"`"); err != nil {
			return fmt.Errorf("dropping trigger %s on the scratch database: %w", n, err)
		}
	}
	return nil
}

// wrapTriggers puts each CREATE TRIGGER between goose's StatementBegin and
// StatementEnd, so goose sends its body as one statement.
func wrapTriggers(ddl string) string {
	return eachTrigger(ddl, func(b *strings.Builder, trigger string) {
		b.WriteString("-- +goose StatementBegin\n" + trigger + "-- +goose StatementEnd\n")
	})
}

// stripTriggers removes every CREATE TRIGGER statement (and the blank line after it).
func stripTriggers(ddl string) string {
	out := eachTrigger(ddl, func(*strings.Builder, string) {})
	for strings.Contains(out, "\n\n\n") {
		out = strings.ReplaceAll(out, "\n\n\n", "\n\n")
	}
	return out
}

// eachTrigger copies ddl, handing each CREATE TRIGGER statement to emit
// instead. A trigger whose header ends in BEGIN ends at the line "END;", any
// other at the first line that ends in a semicolon.
func eachTrigger(ddl string, emit func(b *strings.Builder, trigger string)) string {
	var b, trig strings.Builder
	in, block, depth := false, false, 0
	for _, line := range strings.SplitAfter(ddl, "\n") {
		if line == "" {
			continue
		}
		trimmed := strings.ToLower(strings.TrimSpace(line))
		if !in && strings.HasPrefix(trimmed, "create trigger") {
			in, block, depth = true, strings.HasSuffix(trimmed, "begin"), 0
			trig.Reset()
		}
		if !in {
			b.WriteString(line)
			continue
		}
		trig.WriteString(line)
		// A body may nest BEGIN ... END; blocks: count them, one per line as
		// the schema files and mysqldef write them.
		if strings.HasSuffix(trimmed, "begin") {
			depth++
		}
		if trimmed == "end;" {
			depth--
		}
		if (block && depth == 0) || (!block && strings.HasSuffix(trimmed, ";")) {
			in = false
			emit(&b, trig.String())
		}
	}
	return b.String()
}
