// Command specgen writes the OpenAPI document of the HTTP contract
// (httpapi.SpecYAML) to a file, without starting a server. `go generate
// ./...` runs it; CI fails when the committed file differs.
package main

import (
	"flag"
	"fmt"
	"os"

	"github.com/LeventAksakal/notification-system/internal/httpapi"
)

const header = "# Code generated by internal/httpapi/specgen from the server's code; DO NOT EDIT.\n" +
	"# Change the contract in internal/httpapi (contract.go, api.go), then run `go generate ./internal/httpapi`.\n"

func main() {
	out := flag.String("o", "", "file to write")
	flag.Parse()
	spec, err := httpapi.SpecYAML()
	if err == nil {
		err = os.WriteFile(*out, append([]byte(header), spec...), 0o644) //nolint:gosec // a committed source file, readable like the rest of the tree
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "specgen:", err)
		os.Exit(1)
	}
}
