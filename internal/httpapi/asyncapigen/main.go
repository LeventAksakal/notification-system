// Command asyncapigen writes the AsyncAPI 3.0 document of the WebSocket
// stream (httpapi.AsyncAPIYAML) to a file, without starting a server. `go
// generate ./...` runs it, as it runs specgen for the OpenAPI document.
package main

import (
	"flag"
	"fmt"
	"os"

	"github.com/LeventAksakal/notification-system/internal/httpapi"
)

const header = "# Code generated by internal/httpapi/asyncapigen from the server's code; DO NOT EDIT.\n" +
	"# Change the stream in internal/httpapi (stream_event.go, stream_asyncapi.go), then run `go generate ./internal/httpapi`.\n"

func main() {
	out := flag.String("o", "", "file to write")
	flag.Parse()
	doc, err := httpapi.AsyncAPIYAML()
	if err == nil {
		err = os.WriteFile(*out, append([]byte(header), doc...), 0o644) //nolint:gosec // a committed source file, readable like the rest of the tree
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "asyncapigen:", err)
		os.Exit(1)
	}
}
